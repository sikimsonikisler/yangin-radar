-- Oy tekillestirme.
--
-- Oy ucu daha once hicbir kimlik istemiyordu: ayni kisi bir ihbari sinirsiz kez
-- destekleyip guven puanini sisirebiliyordu. Bu tablo (ihbar, oy veren) ikilisini
-- benzersiz tutar; ayni cihaz ayni ihbara yalnizca bir oy verebilir, fikrini
-- degistirirse oyu guncellenir.

create table vote (
    id bigint generated by default as identity,
    fire_report_id bigint not null,
    voter_id varchar(64) not null,
    confirm boolean not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    primary key (id)
);

alter table vote
    add constraint uk_vote_ihbar_veren unique (fire_report_id, voter_id);

create index idx_vote_ihbar on vote (fire_report_id);
