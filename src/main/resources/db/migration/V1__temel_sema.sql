-- YanginRadar temel semasi (V1)
--
-- Bu dosya Hibernate'in varliklardan urettigi semadan alindi; bu yuzden
-- `ddl-auto: validate` ile birebir uyusur. Elle degistirmeyin - yeni bir alan
-- gerektiginde V2, V3 ... diye yeni bir gocdosyasi ekleyin.
--
-- Not: `enum (...)` sozdizimi H2'ye ozgudur. Postgres'e tasinirken bu sutunlar
-- varchar + check kisitina cevrilmeli.

create table attested_device (
    created_at timestamp(6) with time zone not null,
    last_seen_at timestamp(6) with time zone not null,
    sign_count bigint not null,
    key_id varchar(128) not null,
    attestation_statement blob not null,
    attested_credential_data blob not null,
    primary key (key_id)
);

create table capture_challenge (
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    used_at timestamp(6) with time zone,
    id varchar(64) not null,
    nonce varchar(128) not null,
    amac enum ('ATTEST','CEKIM') not null,
    primary key (id)
);

create table dispatch_record (
    created_at timestamp(6) with time zone not null,
    fire_report_id bigint not null,
    id bigint generated by default as identity,
    payload varchar(4000) not null,
    channel varchar(255) not null,
    state varchar(255) not null,
    primary key (id)
);

create table fire_report (
    brightness float(53),
    confidence integer not null,
    confirm_count integer not null,
    deny_count integer not null,
    dispatched boolean not null,
    lat float(53) not null,
    lon float(53) not null,
    created_at timestamp(6) with time zone not null,
    dispatched_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    updated_at timestamp(6) with time zone not null,
    aciklama varchar(1000),
    external_id varchar(255) unique,
    il varchar(255),
    ilce varchar(255),
    reporter_alias varchar(255),
    reporter_contact varchar(255),
    severity enum ('BUYUK_YANGIN','DUMAN_GORULDU','HIZLA_YAYILIYOR','KUCUK_YANGIN') not null,
    source enum ('RESMI','UYDU','VATANDAS') not null,
    status enum ('BEKLIYOR','DOGRULANDI','INCELENIYOR','REDDEDILDI','SONDURULDU') not null,
    primary key (id)
);

create table photo_evidence (
    camera_captured boolean default false not null,
    capture_accuracy_meters float(53),
    capture_distance_meters float(53),
    capture_lat float(53),
    capture_lon float(53),
    device_attested boolean default false not null,
    distance_meters float(53),
    exif_lat float(53),
    exif_lon float(53),
    score integer not null,
    captured_at timestamp(6) with time zone,
    exif_taken_at timestamp(6) with time zone,
    fire_report_id bigint not null,
    id bigint generated by default as identity,
    size_bytes bigint not null,
    uploaded_at timestamp(6) with time zone not null,
    sha256 varchar(64) not null,
    attested_key_id varchar(128),
    checks varchar(2000),
    content_type varchar(255),
    original_filename varchar(255),
    stored_filename varchar(255) not null,
    verdict enum ('GECERLI','GECERSIZ','SUPHELI') not null,
    primary key (id)
);

